#!/usr/bin/env python3
"""Renders the Home screen shortcut icons from the Material Design Icons
font into home_icons.c (LVGL 8 alpha-only images, recolored at runtime).

    python3 tools/make_home_icons.py path/to/materialdesignicons-webfont.ttf

Needs Pillow. Material Design Icons: Apache License 2.0.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

SIZE = 30
ICONS = [  # (C name, MDI name, codepoint)
    ("home_icon_home", "home", 0xF02DC),
    ("home_icon_printer", "printer-3d-nozzle", 0xF0E5B),
    ("home_icon_calendar", "calendar-month", 0xF0E17),
    ("home_icon_server", "server-network", 0xF048D),
    ("home_icon_stocks", "finance", 0xF081F),
    ("home_icon_makerworld", "cube-outline", 0xF01A7),
    ("home_icon_package", "package-variant-closed", 0xF03D7),
    ("home_icon_flight", "airplane", 0xF001D),
    ("home_icon_pin", "pin", 0xF0403),  # "screen pinned" indicator, top-left
    ("home_icon_ha", "home-assistant", 0xF07D0),
    ("home_icon_phone", "phone", 0xF03F2),
    ("home_icon_jellyfin", "television-play", 0xF0ECF),
    # Forecast page (forecast.ino)
    ("wx_icon_sunny", "weather-sunny", 0xF0599),
    ("wx_icon_night", "weather-night", 0xF0594),
    ("wx_icon_partly", "weather-partly-cloudy", 0xF0595),
    ("wx_icon_cloudy", "weather-cloudy", 0xF0590),
    ("wx_icon_fog", "weather-fog", 0xF0591),
    ("wx_icon_rain", "weather-rainy", 0xF0597),
    ("wx_icon_pouring", "weather-pouring", 0xF0596),
    ("wx_icon_snow", "weather-snowy", 0xF0598),
    ("wx_icon_storm", "weather-lightning", 0xF0593),
]

font = ImageFont.truetype(sys.argv[1], SIZE)
out = ['// Generated by tools/make_home_icons.py - do not edit.',
       '// Material Design Icons (Apache License 2.0), %dx%d, LV_IMG_CF_ALPHA_8BIT.' % (SIZE, SIZE),
       '#include "lvgl.h"', '']
for name, mdi, cp in ICONS:
    img = Image.new("L", (SIZE, SIZE), 0)
    ImageDraw.Draw(img).text((SIZE / 2, SIZE / 2), chr(cp), font=font, fill=255, anchor="mm")
    px = list(img.getdata())
    out.append("// %s" % mdi)
    out.append("static const uint8_t %s_map[] = {" % name)
    for i in range(0, len(px), SIZE):
        out.append("  " + ", ".join("0x%02x" % v for v in px[i:i + SIZE]) + ",")
    out.append("};")
    out.append("const lv_img_dsc_t %s = {" % name)
    out.append("  .header = {.cf = LV_IMG_CF_ALPHA_8BIT, .always_zero = 0, .reserved = 0, .w = %d, .h = %d}," % (SIZE, SIZE))
    out.append("  .data_size = sizeof(%s_map)," % name)
    out.append("  .data = %s_map," % name)
    out.append("};")
    out.append("")
open("home_icons.c", "w").write("\n".join(out))
print("wrote home_icons.c with %d icons" % len(ICONS))
